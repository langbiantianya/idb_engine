package com.kxxnzstdsw.dialect

import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import org.slf4j.LoggerFactory
import java.sql.Connection

/**
 * DuckDB 方言 —— 嵌入式列式 OLAP 数据库。
 *
 * ## 连接约定
 *
 * `host` / `port` 完全忽略，仅由 `database` 字段承载 DuckDB URL 核心部分：
 *
 * | database 取值 | DuckDB JDBC URL | 用途 |
 * | --- | --- | --- |
 * | `""` 或 `":memory:"` | `jdbc:duckdb:` | 嵌入式内存模式（每连接私有 DB） |
 * | `"/path/data.duckdb"` | `jdbc:duckdb:/path/data.duckdb` | 本地 DuckDB 文件（多进程共享，文件锁） |
 * | `"/path/data.csv"` | `jdbc:duckdb:/path/data.csv` | 直查 CSV 文件 |
 * | `"/path/data.parquet"` | `jdbc:duckdb:/path/data.parquet` | 直查 Parquet 文件 |
 * | `"/path/data.json"` | `jdbc:duckdb:/path/data.json` | 直查 JSON 文件 |
 * | `"/path/data.xlsx"` | 预转换临时 .duckdb | POI 读取 Excel → 临时 DuckDB 文件 |
 *
 * ## 方言特性
 *
 * - 默认 schema 名是 `main`（DuckDB 命名约定）
 * - 标识符使用双引号包裹（标准 SQL）
 * - 自增主键用 `GENERATED BY DEFAULT AS IDENTITY`
 * - DDL 重建走原生 `SHOW CREATE TABLE name`（≥0.10）
 * - 不支持 `ON UPDATE CASCADE`：检测到时强制改写为 `NO ACTION`
 * - 嵌入式无用户/权限/触发器概念，对应方法抛 `UnsupportedOperationException`
 * - 存储过程不支持；函数仅支持 `MACRO` / 标量 `FUNCTION`
 */
class DuckDBDialect : DatabaseDialect {
    private val logger = LoggerFactory.getLogger(DuckDBDialect::class.java)

    override val driverName = "Duckdb"
    override val jdbcDriverClassName = "org.duckdb.DuckDBDriver"

    // v2.8: 前端连接表单元数据
    override val displayName = "DuckDB (Embedded OLAP)"
    override val connectionType = ConnectionType.EMBEDDED
    override val requiresHost = false
    override val requiresPort = false
    override val supportsUser = false
    override val supportsPassword = false
    override val supportsSchema = true
    override val supportsCrossDatabase = true      // ATTACH 多文件
    override val jdbcUrlExample = "jdbc:duckdb:/path/to/data.duckdb  (or :memory: / .csv / .parquet / .json / .xlsx)"
    override val capabilities = setOf(
        DialectCapability.ROUTINES,
        DialectCapability.VIEWS,
        DialectCapability.INDEXES,
        DialectCapability.FOREIGN_KEYS,
        DialectCapability.MULTI_SCHEMA,
        DialectCapability.EXPORT,
        DialectCapability.EMBEDDED_MODE,
    )

    override fun buildJdbcUrl(host: String, port: Int, database: String): String {
        // host/port 完全忽略；database 承载 DuckDB URL 主体
        val resolved = if (database.isBlank()) "" else resolveLocalFile(database)
        return "jdbc:duckdb:$resolved"
    }

    /**
     * 处理 Excel → 临时 DuckDB 文件；其他文件直通。
     */
    private fun resolveLocalFile(database: String): String {
        return if (ExcelToDuckDbCache.isExcelFile(database)) {
            ExcelToDuckDbCache.getOrCreate(database)
        } else {
            database
        }
    }

    override fun configureConnectionForStreaming(conn: Connection): Boolean {
        // DuckDB 流式读取无需关闭 autoCommit（PG 才需要）
        return conn.autoCommit
    }

    override fun setSearchPath(conn: Connection, schema: String) {
        if (schema.isBlank()) return
        conn.createStatement().use { stmt ->
            stmt.execute("SET schema = ${quoteIdentifier(schema)}")
        }
    }

    override fun buildSetSearchPathSql(schema: String): String? {
        if (schema.isBlank()) return null
        return "SET schema = ${quoteIdentifier(schema)}"
    }

    override fun quoteIdentifier(identifier: String): String {
        // DuckDB 使用双引号包裹（v2.9 #16 转 DialectUtil.quoteWith）
        return DialectUtil.quoteWith(identifier, '"')
    }

    // region Schema / Database 导航

    override suspend fun listDatabases(conn: Connection): List<String> = withContext(Dispatchers.IO) {
        // DuckDB 的"数据库"概念：通过 ATTACH 关联的 .duckdb 文件 + 内置 system/temp
        // 这里查询 duckdb_databases() 拿到已 attach 的库名
        val databases = mutableSetOf<String>()
        try {
            conn.createStatement().use { stmt ->
                stmt.executeQuery(
                    "SELECT database_name FROM duckdb_databases() " +
                    "WHERE database_name NOT IN ('system', 'temp') " +
                    "ORDER BY database_name"
                ).use { rs ->
                    while (rs.next()) {
                        val name = rs.getString(1) ?: continue
                        if (name.isNotBlank()) databases.add(name)
                    }
                }
            }
        } catch (e: Exception) {
            logger.debug("duckdb_databases() 查询失败: ${e.message}")
        }
        // DuckDB 的默认 schema 名 "main" 同时被业务层当作默认数据库引用 —— 一并返回
        databases.add("main")
        databases.toList().sorted()
    }

    override suspend fun listSchemas(conn: Connection, database: String): List<String> = withContext(Dispatchers.IO) {
        val schemas = mutableListOf<String>()
        conn.createStatement().use { stmt ->
            stmt.executeQuery(
                "SELECT schema_name FROM information_schema.schemata " +
                "WHERE schema_name NOT IN ('information_schema', 'pg_catalog') " +
                "ORDER BY schema_name"
            ).use { rs ->
                while (rs.next()) schemas.add(rs.getString(1) ?: continue)
            }
        }
        if (schemas.isEmpty()) schemas.add("main")
        schemas
    }

    override suspend fun createSchema(conn: Connection, name: String, options: Map<String, String>, ifNotExists: Boolean): Boolean = withContext(Dispatchers.IO) {
        val safeName = sanitizeIdentifier(name, "schema name")
        val ifClause = if (ifNotExists) "IF NOT EXISTS " else ""
        conn.createStatement().use { stmt ->
            stmt.execute("CREATE SCHEMA ${ifClause}${quoteIdentifier(safeName)}")
        }
        true
    }

    override suspend fun deleteSchema(conn: Connection, name: String, ifExists: Boolean): Boolean = withContext(Dispatchers.IO) {
        val safeName = sanitizeIdentifier(name, "schema name")
        val ifClause = if (ifExists) "IF EXISTS " else ""
        conn.createStatement().use { stmt ->
            stmt.execute("DROP SCHEMA ${ifClause}${quoteIdentifier(safeName)}")
        }
        true
    }

