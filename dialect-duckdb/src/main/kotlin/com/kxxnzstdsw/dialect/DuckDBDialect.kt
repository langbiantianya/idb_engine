    override suspend fun listForeignKeys(conn: Connection, tableName: String): List<Map<String, String>> = withContext(Dispatchers.IO) {
        val safeTable = sanitizeIdentifier(tableName, "table name")
        val fks = mutableListOf<Map<String, String>>()
        try {
            // DuckDB 提供 duckdb_constraints() 一次性返回所有约束信息
            conn.prepareStatement(
                "SELECT constraint_name, constraint_text, constraint_type " +
                "FROM duckdb_constraints() " +
                "WHERE table_name = ? AND constraint_type = 'FOREIGN KEY'"
            ).use { stmt ->
                stmt.setString(1, safeTable)
                stmt.executeQuery().use { rs ->
                    while (rs.next()) {
                        val name = rs.getString("constraint_name") ?: continue
                        val text = rs.getString("constraint_text") ?: ""
                        val parsed = parseForeignKeyText(text)
                        fks.add(mapOf(
                            "name" to name,
                            "table" to safeTable,
                            "columns" to parsed.columns.joinToString(","),
                            "ref_table" to parsed.refTable,
                            "ref_columns" to parsed.refColumns.joinToString(","),
                            "on_delete" to parsed.onDelete,
                            "on_update" to parsed.onUpdate
                        ))
                    }
                }
            }
        } catch (e: Exception) {
            logger.debug("duckdb_constraints() 查询失败: ${e.message}")
        }
        fks
    }

    /**
     * 解析 DuckDB 的 FK 约束文本，形如：
     * "FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE ON UPDATE NO ACTION"
     */
    private data class ParsedFk(val columns: List<String>, val refTable: String, val refColumns: List<String>, val onDelete: String, val onUpdate: String)

    private fun parseForeignKeyText(text: String): ParsedFk {
        // columns
        val colMatch = Regex("""FOREIGN\s+KEY\s*\(([^)]+)\)""", RegexOption.IGNORE_CASE).find(text)
        val columns = colMatch?.groupValues?.get(1)?.split(",")?.map { it.trim() } ?: emptyList()
        // ref table + ref columns
        val refMatch = Regex("""REFERENCES\s+([^\s(]+)\s*\(([^)]+)\)""", RegexOption.IGNORE_CASE).find(text)
        val refTable = refMatch?.groupValues?.get(1)?.trim() ?: ""
        val refColumns = refMatch?.groupValues?.get(2)?.split(",")?.map { it.trim() } ?: emptyList()
        // on delete / on update
        val onDelete = Regex("""ON\s+DELETE\s+([A-Z_]+)""", RegexOption.IGNORE_CASE).find(text)?.groupValues?.get(1) ?: "NO ACTION"
        val onUpdate = Regex("""ON\s+UPDATE\s+([A-Z_]+)""", RegexOption.IGNORE_CASE).find(text)?.groupValues?.get(1) ?: "NO ACTION"
        return ParsedFk(columns, refTable, refColumns, onDelete.uppercase(), onUpdate.uppercase())
    }

    override suspend fun addForeignKey(
        conn: Connection,
        tableName: String,
        fkName: String,
        columns: List<String>,
        refTable: String,
        refColumns: List<String>,
        onDelete: String?,
        onUpdate: String?
    ): Boolean = withContext(Dispatchers.IO) {
        val safeTable = sanitizeIdentifier(tableName, "table name")
        val safeFk = sanitizeIdentifier(fkName, "foreign key name")
        val cols = columns.joinToString(", ") { quoteIdentifier(it) }
        val refCols = refColumns.joinToString(", ") { quoteIdentifier(it) }
        // DuckDB 不支持 ON UPDATE CASCADE —— 强制改写为 NO ACTION 并日志 warn
        val effectiveOnUpdate = if (onUpdate?.uppercase() == "CASCADE") {
            logger.warn("Duckdb 不支持 ON UPDATE CASCADE，已自动改写为 NO ACTION (FK=$safeFk)")
            "NO ACTION"
        } else {
            onUpdate
        }
        // DuckDB 同样不支持 ON DELETE CASCADE / SET NULL / SET DEFAULT —— 强制改写为 NO ACTION
        val effectiveOnDelete = if (onDelete?.uppercase() in setOf("CASCADE", "SET NULL", "SET DEFAULT")) {
            logger.warn("Duckdb 不支持 ON DELETE $onDelete，已自动改写为 NO ACTION (FK=$safeFk)")
            "NO ACTION"
        } else {
            onDelete
        }
        // DuckDB 不支持 ALTER TABLE ADD CONSTRAINT —— 通过"创建临时新表 → 复制数据 → 改名"的方式重建
        val fkInline = buildString {
            append("FOREIGN KEY ($cols) REFERENCES ${quoteIdentifier(refTable)} ($refCols)")
            effectiveOnDelete?.takeIf { it.isNotBlank() }?.let { append(" ON DELETE $it") }
            effectiveOnUpdate?.takeIf { it.isNotBlank() }?.let { append(" ON UPDATE $it") }
        }
        rebuildTableWithExtraConstraint(conn, safeTable, extraConstraintSql = "CONSTRAINT ${quoteIdentifier(safeFk)} $fkInline")
        true
    }

    override suspend fun dropForeignKey(conn: Connection, tableName: String, fkName: String, ifExists: Boolean): Boolean = withContext(Dispatchers.IO) {
        val safeTable = sanitizeIdentifier(tableName, "table name")
        val safeFk = sanitizeIdentifier(fkName, "foreign key name")
        // 1) 先按用户给出的名称精确查找
        var actualFkName = safeFk
        var exists = conn.prepareStatement(
            "SELECT constraint_name FROM duckdb_constraints() WHERE table_name = ? AND constraint_name = ? AND constraint_type = 'FOREIGN KEY' LIMIT 1"
        ).use { stmt ->
            stmt.setString(1, safeTable)
            stmt.setString(2, safeFk)
            stmt.executeQuery().use { rs -> if (rs.next()) rs.getString(1) else null }
        }
        // 2) DuckDB 1.x 会忽略 CREATE TABLE 中的 CONSTRAINT 子句名并自动生成 <table>_<cols>_fkey；
        //    此时若表上仅 1 个 FK，则把该 FK 视作目标（业务约定：业务层 drop FK 时若约束名失配即按唯一匹配兜底）
        if (exists == null) {
            val fkList = mutableListOf<String>()
            conn.prepareStatement(
                "SELECT constraint_name FROM duckdb_constraints() WHERE table_name = ? AND constraint_type = 'FOREIGN KEY' ORDER BY constraint_name"
            ).use { stmt ->
                stmt.setString(1, safeTable)
                stmt.executeQuery().use { rs -> while (rs.next()) rs.getString(1)?.let { fkList.add(it) } }
            }
            when {
                fkList.size == 1 -> {
                    actualFkName = fkList.first()
                    exists = actualFkName
                    logger.warn("Duckdb 忽略了用户给定的 FK 约束名 '$safeFk'，实际约束名为 '$actualFkName'，已按唯一匹配兜底删除")
                }
                fkList.isEmpty() -> {
                    if (!ifExists) throw IllegalArgumentException("外键 '$safeFk' 不存在")
                    return@withContext true
                }
                else -> throw IllegalArgumentException("外键 '$safeFk' 不存在且表上有多个 FK (${fkList.joinToString()})，无法确定目标")
            }
        }
        rebuildTableExcludingConstraint(conn, safeTable, constraintName = actualFkName)
        true
    }

    /**
     * 重建表，追加额外约束（用于 addForeignKey）。
     * 步骤：备份数据 → DROP → CREATE（同列定义 + extraConstraintSql）→ 数据回填
     */
    private fun rebuildTableWithExtraConstraint(
        conn: Connection,
        tableName: String,
        extraConstraintSql: String
    ) {
        // 1. 取出原表 DDL（去除外键约束后的精简版）
        val colDefs = mutableListOf<String>()
        conn.prepareStatement(
            "SELECT column_name, data_type, is_nullable, column_default FROM information_schema.columns " +
            "WHERE table_name = ? ORDER BY ordinal_position"
        ).use { stmt ->
            stmt.setString(1, tableName)
            stmt.executeQuery().use { rs ->
                while (rs.next()) {
                    colDefs.add(buildColumnDefForDdl(
                        rs.getString("column_name") ?: continue,
                        rs.getString("data_type") ?: "",
                        "YES".equals(rs.getString("is_nullable"), ignoreCase = true),
                        rs.getString("column_default")
                    ))
                }
            }
        }
        // 2. 主键约束
        val pkCols = mutableListOf<String>()
        conn.prepareStatement(
            "SELECT kcu.column_name FROM information_schema.key_column_usage kcu " +
            "JOIN information_schema.table_constraints tc ON kcu.constraint_name = tc.constraint_name AND kcu.table_schema = tc.table_schema " +
            "WHERE tc.constraint_type = 'PRIMARY KEY' AND kcu.table_name = ? ORDER BY kcu.ordinal_position"
        ).use { stmt ->
            stmt.setString(1, tableName)
            stmt.executeQuery().use { rs -> while (rs.next()) pkCols.add(rs.getString(1) ?: continue) }
        }
        if (pkCols.isNotEmpty()) colDefs.add("PRIMARY KEY (${pkCols.joinToString(", ") { quoteIdentifier(it) }})")
        colDefs.add(extraConstraintSql)

        val createDdl = "CREATE TABLE ${quoteIdentifier(tableName)} (\n  " +
            colDefs.joinToString(",\n  ") + "\n)"

        // 3. 备份 → DROP → CREATE → 数据回填
        val tempName = "${tableName}_tmp_${System.currentTimeMillis()}"
        conn.createStatement().use { stmt ->
            stmt.execute("CREATE TABLE ${quoteIdentifier(tempName)} AS SELECT * FROM ${quoteIdentifier(tableName)}")
            stmt.execute("DROP TABLE ${quoteIdentifier(tableName)}")
            stmt.execute(createDdl)
            stmt.execute("INSERT INTO ${quoteIdentifier(tableName)} SELECT * FROM ${quoteIdentifier(tempName)}")
            stmt.execute("DROP TABLE ${quoteIdentifier(tempName)}")
        }
    }

    /**
     * 重建表，排除指定外键约束（用于 dropForeignKey）。
     */
    private fun rebuildTableExcludingConstraint(
        conn: Connection,
        tableName: String,
        constraintName: String
    ) {
        val colDefs = mutableListOf<String>()
        conn.prepareStatement(
            "SELECT column_name, data_type, is_nullable, column_default FROM information_schema.columns " +
            "WHERE table_name = ? ORDER BY ordinal_position"
        ).use { stmt ->
            stmt.setString(1, tableName)
            stmt.executeQuery().use { rs ->
                while (rs.next()) {
                    colDefs.add(buildColumnDefForDdl(
                        rs.getString("column_name") ?: continue,
                        rs.getString("data_type") ?: "",
                        "YES".equals(rs.getString("is_nullable"), ignoreCase = true),
                        rs.getString("column_default")
                    ))
                }
            }
        }
        // 主键
        val pkCols = mutableListOf<String>()
        conn.prepareStatement(
            "SELECT kcu.column_name FROM information_schema.key_column_usage kcu " +
            "JOIN information_schema.table_constraints tc ON kcu.constraint_name = tc.constraint_name AND kcu.table_schema = tc.table_schema " +
            "WHERE tc.constraint_type = 'PRIMARY KEY' AND kcu.table_name = ? ORDER BY kcu.ordinal_position"
        ).use { stmt ->
            stmt.setString(1, tableName)
            stmt.executeQuery().use { rs -> while (rs.next()) pkCols.add(rs.getString(1) ?: continue) }
        }
        if (pkCols.isNotEmpty()) colDefs.add("PRIMARY KEY (${pkCols.joinToString(", ") { quoteIdentifier(it) }})")

        // 保留的 UNIQUE 约束（排除要删除的 FK）
        conn.prepareStatement(
            "SELECT kcu.column_name, kcu.constraint_name FROM information_schema.key_column_usage kcu " +
            "JOIN information_schema.table_constraints tc ON kcu.constraint_name = tc.constraint_name AND kcu.table_schema = tc.table_schema " +
            "WHERE tc.constraint_type = 'UNIQUE' AND kcu.table_name = ? AND kcu.constraint_name != ? " +
            "ORDER BY kcu.constraint_name, kcu.ordinal_position"
        ).use { stmt ->
            stmt.setString(1, tableName)
            stmt.setString(2, constraintName)
            val grouped = mutableMapOf<String, MutableList<String>>()
            stmt.executeQuery().use { rs ->
                while (rs.next()) {
                    val col = rs.getString(1) ?: continue
                    val cn = rs.getString(2) ?: continue
                    grouped.getOrPut(cn) { mutableListOf() }.add(col)
                }
            }
            for ((cn, cols) in grouped) {
                colDefs.add("CONSTRAINT ${quoteIdentifier(cn)} UNIQUE (${cols.joinToString(", ") { quoteIdentifier(it) }})")
            }
        }
        // 保留的其他 FK（排除要删除的）
        conn.prepareStatement(
            "SELECT constraint_name, constraint_text FROM duckdb_constraints() " +
            "WHERE table_name = ? AND constraint_type = 'FOREIGN KEY' AND constraint_name != ?"
        ).use { stmt ->
            stmt.setString(1, tableName)
            stmt.setString(2, constraintName)
            stmt.executeQuery().use { rs ->
                while (rs.next()) {
                    val cn = rs.getString("constraint_name") ?: continue
                    val text = rs.getString("constraint_text") ?: continue
                    colDefs.add("CONSTRAINT ${quoteIdentifier(cn)} $text")
                }
            }
        }

        val createDdl = "CREATE TABLE ${quoteIdentifier(tableName)} (\n  " +
            colDefs.joinToString(",\n  ") + "\n)"

        val tempName = "${tableName}_tmp_${System.currentTimeMillis()}"
        conn.createStatement().use { stmt ->
            stmt.execute("CREATE TABLE ${quoteIdentifier(tempName)} AS SELECT * FROM ${quoteIdentifier(tableName)}")
            stmt.execute("DROP TABLE ${quoteIdentifier(tableName)}")
            stmt.execute(createDdl)
            stmt.execute("INSERT INTO ${quoteIdentifier(tableName)} SELECT * FROM ${quoteIdentifier(tempName)}")
            stmt.execute("DROP TABLE ${quoteIdentifier(tempName)}")
        }
    }

