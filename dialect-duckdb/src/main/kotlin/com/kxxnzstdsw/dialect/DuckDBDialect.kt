    override suspend fun listTables(conn: Connection, database: String, schema: String): List<Map<String, String>> = withContext(Dispatchers.IO) {
        val tables = mutableListOf<Map<String, String>>()
        val targetSchema = schema.ifBlank { "main" }
        val query = """
            SELECT table_name, table_type
            FROM information_schema.tables
            WHERE table_schema = ?
            ORDER BY table_name
        """.trimIndent()
        conn.prepareStatement(query).use { stmt ->
            stmt.setString(1, targetSchema)
            stmt.executeQuery().use { rs ->
                while (rs.next()) {
                    tables.add(mapOf(
                        "name" to (rs.getString("table_name") ?: ""),
                        "type" to (rs.getString("table_type") ?: "BASE TABLE")
                    ))
                }
            }
        }
        tables
    }

    /**
     * DuckDB listColumns：使用 information_schema.columns + key_column_usage。
     * 注：duckdb_constraints() 没有 column_name 列（只有 constraint_column_names LIST），
     *     因此主键解析直接走 information_schema.key_column_usage。
     */
    override suspend fun listColumns(
        conn: Connection,
        database: String,
        schema: String,
        tableName: String
    ): List<Map<String, Any?>> = withContext(Dispatchers.IO) {
        val targetSchema = schema.ifBlank { "main" }
        val columns = mutableListOf<Map<String, Any?>>()

        // 1. 主键列表 —— information_schema.key_column_usage 是 DuckDB 1.x 稳定路径
        val primaryKeys = mutableSetOf<String>()
        conn.prepareStatement(
            "SELECT kcu.column_name FROM information_schema.key_column_usage kcu " +
            "JOIN information_schema.table_constraints tc " +
            "  ON kcu.constraint_name = tc.constraint_name AND kcu.table_schema = tc.table_schema " +
            "WHERE tc.constraint_type = 'PRIMARY KEY' " +
            "  AND kcu.table_name = ? AND kcu.table_schema = ?"
        ).use { stmt ->
            stmt.setString(1, tableName)
            stmt.setString(2, targetSchema)
            stmt.executeQuery().use { rs ->
                while (rs.next()) primaryKeys.add(rs.getString(1) ?: continue)
            }
        }

        // 2. 列定义
        conn.prepareStatement(
            "SELECT column_name, data_type, is_nullable, column_default " +
            "FROM information_schema.columns " +
            "WHERE table_name = ? AND table_schema = ? " +
            "ORDER BY ordinal_position"
        ).use { stmt ->
            stmt.setString(1, tableName)
            stmt.setString(2, targetSchema)
            stmt.executeQuery().use { rs ->
                while (rs.next()) {
                    val name = rs.getString("column_name") ?: continue
                    val dataType = rs.getString("data_type") ?: ""
                    val nullable = rs.getString("is_nullable")
                    val defaultVal = rs.getString("column_default")
                    columns.add(mapOf(
                        "name" to name,
                        "type" to dataType,
                        "size" to extractSize(dataType),
                        "nullable" to ("YES".equals(nullable, ignoreCase = true)),
                        "isPrimaryKey" to (name in primaryKeys),
                        "defaultValue" to defaultVal
                    ))
                }
            }
        }
        columns
    }

    /**
     * 从 DuckDB 类型字符串提取 size —— 例如 VARCHAR(255) → 255, DECIMAL(10,2) → 10
     */
    private fun extractSize(dataType: String): Int {
        val match = Regex("""\(\s*(\d+)""").find(dataType) ?: return 0
        return match.groupValues[1].toIntOrNull() ?: 0
    }

