    // region DDL 构建

    override fun buildColumnDefinition(
        name: String,
        type: String,
        size: Int?,
        nullable: Boolean,
        isPrimaryKey: Boolean,
        defaultValue: String?,
        autoIncrement: Boolean
    ): String = buildString {
        append(quoteIdentifier(name))
        append(" ")
        when {
            // 自增主键：DuckDB 1.5.5 不支持 GENERATED BY DEFAULT AS IDENTITY 与表级 PK 组合
            // （报 "Constraint not implemented"），也不支持 INTEGER PRIMARY KEY 的 ROWID 自动填充。
            // 唯一可行：DuckDB 显式 CREATE SEQUENCE + 列 DEFAULT nextval(...) + 表级 PRIMARY KEY。
            autoIncrement && isPrimaryKey -> {
                append(buildTypeSpec(type, size))
                append(" DEFAULT nextval('")
                append(autoIncrementSequenceName(name))
                append("')")
            }
            // 非主键的自增：使用 IDENTITY 语法
            autoIncrement -> {
                append(buildTypeSpec(type, size))
                append(" GENERATED BY DEFAULT AS IDENTITY")
            }
            else -> append(buildTypeSpec(type, size))
        }
        if (!autoIncrement && !nullable) append(" NOT NULL")
        if (defaultValue != null && !autoIncrement) {
            append(" DEFAULT ")
            append(if (UNQUOTED_DEFAULT_REGEX.matches(defaultValue)) {
                defaultValue
            } else {
                "'${defaultValue.replace("'", "''")}'"
            })
        }
    }

    /** DuckDB 自增主键列绑定的 SEQUENCE 命名约定：seq_<colname>。 */
    private fun autoIncrementSequenceName(columnName: String): String = "seq_$columnName"

    /**
     * DuckDB 自增主键需要在 CREATE TABLE 之前先 CREATE SEQUENCE —— DEFAULT nextval 必须能找到序列。
     * 通过 buildPreCreateStatements 钩子实现（v2.7 SPI 扩展）。
     */
    override fun buildPreCreateStatements(tableName: String, autoIncrementColumns: List<String>): List<String> =
        autoIncrementColumns.map { col ->
            "CREATE SEQUENCE IF NOT EXISTS ${autoIncrementSequenceName(col)} START 1"
        }

    override fun buildAddColumnSQL(tableName: String, columnDef: String): String {
        return "ALTER TABLE ${quoteIdentifier(tableName)} ADD COLUMN $columnDef"
    }

    override fun buildDropColumnSQL(tableName: String, columnName: String): String {
        return "ALTER TABLE ${quoteIdentifier(tableName)} DROP COLUMN ${quoteIdentifier(columnName)}"
    }

    /**
     * DuckDB 支持单条 ALTER TABLE ... ALTER COLUMN ... SET TYPE 等子句，
     * 一次只能改一个属性（type / rename / set default / drop default / set not null / drop not null）。
     */
    override fun buildModifyColumnSQL(
        tableName: String,
        name: String,
        type: String?,
        size: Int?,
        nullable: Boolean,
        defaultValue: String?,
        newName: String?
    ): String {
        val table = quoteIdentifier(tableName)
        val col = quoteIdentifier(name)
        return when {
            !type.isNullOrBlank() -> {
                val typeSpec = buildTypeSpec(type, size)
                "ALTER TABLE $table ALTER COLUMN $col SET DATA TYPE $typeSpec"
            }
            newName != null -> "ALTER TABLE $table RENAME COLUMN $col TO ${quoteIdentifier(newName)}"
            defaultValue != null -> {
                val literal = if (UNQUOTED_DEFAULT_REGEX.matches(defaultValue)) {
                    defaultValue
                } else {
                    "'${defaultValue.replace("'", "''")}'"
                }
                "ALTER TABLE $table ALTER COLUMN $col SET DEFAULT $literal"
            }
            !nullable -> "ALTER TABLE $table ALTER COLUMN $col SET NOT NULL"
            nullable -> "ALTER TABLE $table ALTER COLUMN $col DROP NOT NULL"
            else -> throw IllegalArgumentException("MODIFY_COLUMN 调用缺少任何修改属性")
        }
    }

    /**
     * DuckDB 1.5.x 不支持 `SHOW CREATE TABLE`。从 information_schema.columns + 约束信息手工重建。
     */
    override suspend fun getCreateTableDDL(conn: Connection, tableName: String): String = withContext(Dispatchers.IO) {
        val safeTable = sanitizeIdentifier(tableName, "table name")
        // 1. 列定义
        val colDefs = mutableListOf<String>()
        var tableExists = false
        conn.prepareStatement(
            "SELECT column_name, data_type, is_nullable, column_default " +
            "FROM information_schema.columns " +
            "WHERE table_name = ? ORDER BY ordinal_position"
        ).use { stmt ->
            stmt.setString(1, safeTable)
            stmt.executeQuery().use { rs ->
                while (rs.next()) {
                    tableExists = true
                    val name = rs.getString("column_name") ?: continue
                    val type = rs.getString("data_type") ?: ""
                    val nullable = "YES".equals(rs.getString("is_nullable"), ignoreCase = true)
                    val def = rs.getString("column_default")
                    colDefs.add(buildColumnDefForDdl(name, type, nullable, def))
                }
            }
        }
        if (!tableExists) throw IllegalArgumentException("未找到表 '$safeTable'")

        // 2. 主键约束
        val pkCols = mutableListOf<String>()
        conn.prepareStatement(
            "SELECT kcu.column_name FROM information_schema.key_column_usage kcu " +
            "JOIN information_schema.table_constraints tc " +
            "  ON kcu.constraint_name = tc.constraint_name AND kcu.table_schema = tc.table_schema " +
            "WHERE tc.constraint_type = 'PRIMARY KEY' AND kcu.table_name = ? " +
            "ORDER BY kcu.ordinal_position"
        ).use { stmt ->
            stmt.setString(1, safeTable)
            stmt.executeQuery().use { rs ->
                while (rs.next()) pkCols.add(rs.getString(1) ?: continue)
            }
        }
        if (pkCols.isNotEmpty()) {
            colDefs.add("PRIMARY KEY (${pkCols.joinToString(", ") { quoteIdentifier(it) }})")
        }

        // 3. UNIQUE 约束
        conn.prepareStatement(
            "SELECT kcu.column_name, kcu.constraint_name FROM information_schema.key_column_usage kcu " +
            "JOIN information_schema.table_constraints tc " +
            "  ON kcu.constraint_name = tc.constraint_name AND kcu.table_schema = tc.table_schema " +
            "WHERE tc.constraint_type = 'UNIQUE' AND kcu.table_name = ? " +
            "ORDER BY kcu.constraint_name, kcu.ordinal_position"
        ).use { stmt ->
            stmt.setString(1, safeTable)
            val grouped = mutableMapOf<String, MutableList<String>>()
            stmt.executeQuery().use { rs ->
                while (rs.next()) {
                    val col = rs.getString(1) ?: continue
                    val cn = rs.getString(2) ?: continue
                    grouped.getOrPut(cn) { mutableListOf() }.add(col)
                }
            }
            for ((cn, cols) in grouped) {
                colDefs.add("CONSTRAINT ${quoteIdentifier(cn)} UNIQUE (${cols.joinToString(", ") { quoteIdentifier(it) }})")
            }
        }

        // 4. 外键约束
        val fkText = mutableListOf<String>()
        conn.prepareStatement(
            "SELECT constraint_name, constraint_text FROM duckdb_constraints() " +
            "WHERE table_name = ? AND constraint_type = 'FOREIGN KEY'"
        ).use { stmt ->
            stmt.setString(1, safeTable)
            stmt.executeQuery().use { rs ->
                while (rs.next()) {
                    val cn = rs.getString("constraint_name") ?: continue
                    val text = rs.getString("constraint_text") ?: continue
                    fkText.add("CONSTRAINT ${quoteIdentifier(cn)} $text")
                }
            }
        }
        colDefs.addAll(fkText)

        return@withContext "CREATE TABLE ${quoteIdentifier(safeTable)} (\n  " +
            colDefs.joinToString(",\n  ") + "\n)"
    }

    /**
     * 从 information_schema 反推列定义 DDL 片段。
     */
    private fun buildColumnDefForDdl(
        name: String,
        dataType: String,
        nullable: Boolean,
        defaultExpr: String?
    ): String {
        val sb = StringBuilder()
        sb.append(quoteIdentifier(name)).append(' ').append(dataType)
        if (!nullable) sb.append(" NOT NULL")
        if (!defaultExpr.isNullOrBlank()) sb.append(" DEFAULT ").append(defaultExpr)
        return sb.toString()
    }

    override fun buildTableOptionsSQL(options: Map<String, String>): String = "" // DuckDB 无表级选项

    override fun buildPostCreateStatements(tableName: String, options: Map<String, String>): List<String> {
        // DuckDB 支持 COMMENT ON TABLE
        val statements = mutableListOf<String>()
        val comment = options["comment"]
        if (!comment.isNullOrBlank()) {
            val escaped = comment.replace("'", "''")
            statements.add("COMMENT ON TABLE ${quoteIdentifier(tableName)} IS '$escaped'")
        }
        return statements
    }

