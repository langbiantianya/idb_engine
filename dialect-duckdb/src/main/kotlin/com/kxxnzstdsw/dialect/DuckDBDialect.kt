                        val isUnique = rs.getBoolean("is_unique")
                        val isPrimary = rs.getBoolean("is_primary")
                        // 解析列名 —— DuckDB 的 sql 形如 "CREATE INDEX [UNIQUE] INDEX name ON table (cols)"
                        val cols = extractIndexColumns(sql)
                        indexes.add(mapOf(
                            "name" to name,
                            "table" to safeTable,
                            "columns" to cols,
                            "unique" to isUnique.toString(),
                            "primary" to isPrimary.toString(),
                            "type" to "ART"
                        ))
                    }
                }
            }
        } catch (e: Exception) {
            logger.debug("duckdb_indexes() 查询失败: ${e.message}")
        }
        indexes
    }

    private fun extractIndexColumns(sql: String): String {
        // 例："CREATE INDEX idx_users_name ON main.users (name, age)"
        val match = Regex("""\(\s*([^)]+)\s*\)""").find(sql) ?: return ""
        return match.groupValues[1].split(",").joinToString(",") { it.trim() }
    }

